"""Step 2: learn the Detector rules from labelled windows and measure them.

Usage:
    python3 python/train_rules.py config.json

Reads build/records/*.npz (from extract.py) and writes:
    build/rules.json        the learned depth-3 tree, integer thresholds
    rtl/rules.vh            the same tree as a Verilog function
    c/rules.h               the same tree as a C function
    results/learned_rules.txt       the tree in plain words
    results/detection_metrics.md    precision, recall, F1 per class on the TEST split,
                            confusion matrix, alarm delay and false alarms per
                            test capture, and the teammates' hand rule for
                            comparison
    results/window_counts_<capture>.png   counts per window, attack windows shaded

Window label: a window is labelled with the capture's attack class if it holds
at least one attack packet (see extract.py), otherwise "normal".
Training uses only captures with split "train"; all numbers in detection_metrics.md come
from captures with split "test". random_state is fixed, so reruns give the
same tree.
"""

import json
import os
import sys

import numpy as np
from sklearn.tree import DecisionTreeClassifier

sys.path.insert(0, os.path.dirname(__file__))
from common import (CLASS_ID, CLASSES, FEATURES, TICK_US, WINDOW_TICKS,  # noqa: E402
                    classify, floor_threshold, run_detector, window_counts)

MAX_DEPTH = 3
HAND_RULE = {"feature": "modbus", "min": 8, "persist": 3}   # teammates' rule


def capture_name(entry):
    return entry.get("name") or os.path.splitext(os.path.basename(entry["file"]))[0]


def load_windows(base, entry):
    d = np.load(os.path.join(base, "build", "records", capture_name(entry) + ".npz"))
    ticks = d["ts_us"] // TICK_US
    counts = window_counts(ticks, d["kind"])
    att = np.zeros(len(counts), int)
    for t in ticks[d["is_attack"]]:
        att[int(t) // WINDOW_TICKS] += 1
    cls = CLASS_ID[entry["scenario"]]
    labels = [cls if a > 0 else 0 for a in att]
    return np.array(counts, dtype=np.int64), np.array(labels, dtype=np.int64)


def export_tree(clf):
    t = clf.tree_
    nodes = []
    for i in range(t.node_count):
        if t.children_left[i] == -1:
            nodes.append({"leaf": int(clf.classes_[int(np.argmax(t.value[i][0]))])})
        else:
            nodes.append({"feature": int(t.feature[i]),
                          "threshold": floor_threshold(t.threshold[i]),
                          "left": int(t.children_left[i]),
                          "right": int(t.children_right[i])})
    return {"features": FEATURES, "classes": CLASSES, "max_depth": MAX_DEPTH, "nodes": nodes}


def tree_to_code(rules, lang):
    lines = []

    def walk(i, depth):
        n = rules["nodes"][i]
        pad = "    " * depth
        if "leaf" in n:
            if lang == "v":
                lines.append("%sclassify = 2'd%d;  // %s" % (pad, n["leaf"], CLASSES[n["leaf"]]))
            elif lang == "c":
                lines.append("%sreturn %d;  /* %s */" % (pad, n["leaf"], CLASSES[n["leaf"]]))
            else:
                lines.append("%s-> %s" % (pad, CLASSES[n["leaf"]]))
            return
        f = FEATURES[n["feature"]]
        if lang == "v":
            lines.append("%sif (%s <= 16'd%d) begin" % (pad, f, n["threshold"]))
            walk(n["left"], depth + 1)
            lines.append("%send else begin" % pad)
            walk(n["right"], depth + 1)
            lines.append("%send" % pad)
        elif lang == "c":
            lines.append("%sif (%s <= %d) {" % (pad, f, n["threshold"]))
            walk(n["left"], depth + 1)
            lines.append("%s} else {" % pad)
            walk(n["right"], depth + 1)
            lines.append("%s}" % pad)
        else:
            lines.append("%sif %s count <= %d per 100 ms:" % (pad, f, n["threshold"]))
            walk(n["left"], depth + 1)
            lines.append("%selse:" % pad)
            walk(n["right"], depth + 1)

    walk(0, 2 if lang in ("v",) else 1)
    return lines


def write_generated(root, rules):
    v = ["// GENERATED by python/train_rules.py. Do not edit by hand.",
         "// Learned depth-%d decision tree. Inputs are per-window counts." % MAX_DEPTH,
         "function [1:0] classify;",
         "    input [15:0] icmp;",
         "    input [15:0] syn;",
         "    input [15:0] modbus;",
         "    input [15:0] other;",
         "    begin"] + tree_to_code(rules, "v") + ["    end", "endfunction", ""]
    with open(os.path.join(root, "rtl", "rules.vh"), "w") as f:
        f.write("\n".join(v))
    c = ["/* GENERATED by python/train_rules.py. Do not edit by hand. */",
         "#ifndef RULES_H", "#define RULES_H", "#include <stdint.h>",
         "static inline int classify(uint32_t icmp, uint32_t syn, uint32_t modbus, uint32_t other) {",
         "    (void)icmp; (void)syn; (void)modbus; (void)other;"] + tree_to_code(rules, "c") + \
        ["}", "#endif", ""]
    with open(os.path.join(root, "c", "rules.h"), "w") as f:
        f.write("\n".join(c))
    with open(os.path.join(root, "results", "learned_rules.txt"), "w") as f:
        f.write("\n".join(["Learned rules (depth-%d tree), counts per 100 ms window:" % MAX_DEPTH, ""]
                          + tree_to_code(rules, "txt")) + "\n")


def prf(y_true, y_pred, k):
    tp = int(np.sum((y_pred == k) & (y_true == k)))
    fp = int(np.sum((y_pred == k) & (y_true != k)))
    fn = int(np.sum((y_pred != k) & (y_true == k)))
    p = tp / (tp + fp) if tp + fp else float("nan")
    r = tp / (tp + fn) if tp + fn else float("nan")
    f1 = 2 * p * r / (p + r) if p == p and r == r and p + r > 0 else float("nan")
    return p, r, f1, int(np.sum(y_true == k))


def hand_rule_alarms(counts):
    col = FEATURES.index(HAND_RULE["feature"])
    run, out = 0, []
    for c in counts:
        run = run + 1 if c[col] >= HAND_RULE["min"] else 0
        out.append(1 if run >= HAND_RULE["persist"] else 0)
    return np.array(out)


def alarm_stats(alarms, labels):
    att = np.where(labels > 0)[0]
    first_att = int(att[0]) if len(att) else -1
    fired = np.where(alarms == 1)[0]
    first_alarm = int(fired[0]) if len(fired) else -1
    false_alarms = int(np.sum((alarms == 1) & (labels == 0)))
    delay = (first_alarm - first_att) * 100 if first_att >= 0 and first_alarm >= first_att else None
    return first_att, first_alarm, delay, false_alarms


def plot(path, name, counts, labels):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    t = np.arange(len(counts)) * 0.1
    fig, ax = plt.subplots(figsize=(9, 3.2))
    for i, f in enumerate(FEATURES):
        ax.plot(t, counts[:, i], label=f, linewidth=1)
    att = labels > 0
    if att.any():
        ax.fill_between(t, 0, 1, where=att, transform=ax.get_xaxis_transform(), alpha=0.12,
                        color="red", label="attack windows")
    ax.set_xlabel("time (s)")
    ax.set_ylabel("packets per 100 ms")
    ax.set_title(name)
    ax.legend(loc="upper right", fontsize=8)
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    plt.close(fig)


def main(cfg_path):
    with open(cfg_path) as f:
        cfg = json.load(f)
    base = os.path.dirname(os.path.abspath(cfg_path))
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    os.makedirs(os.path.join(base, "results"), exist_ok=True)
    os.makedirs(os.path.join(root, "results"), exist_ok=True)

    data = {}
    for e in cfg["captures"]:
        data[capture_name(e)] = (e,) + load_windows(base, e)

    tr = [v for v in data.values() if v[0].get("split") == "train"]
    te = [v for v in data.values() if v[0].get("split") == "test"]
    if not tr or not te:
        raise SystemExit("config needs captures with split 'train' and split 'test'")
    Xtr = np.vstack([v[1] for v in tr])
    ytr = np.concatenate([v[2] for v in tr])
    clf = DecisionTreeClassifier(max_depth=MAX_DEPTH, random_state=0, class_weight="balanced")
    clf.fit(Xtr, ytr)
    rules = export_tree(clf)
    os.makedirs(os.path.join(base, "build"), exist_ok=True)
    with open(os.path.join(base, "build", "rules.json"), "w") as f:
        json.dump(rules, f, indent=1)
    write_generated(root, rules)

    # evaluate with the EXPORTED integer rules, exactly what hardware runs
    Xte = np.vstack([v[1] for v in te])
    yte = np.concatenate([v[2] for v in te])
    pred = np.array([classify(rules, list(map(int, x))) for x in Xte])
    agree = float(np.mean(pred == clf.predict(Xte)))

    md = ["# Metrics (test split only)", "",
          "Training windows: %d, test windows: %d. Exported rules agree with sklearn on %.4f of test windows."
          % (len(ytr), len(yte), agree), "",
          "## Per-window precision, recall, F1", "",
          "| class | precision | recall | F1 | test windows |", "| --- | --- | --- | --- | --- |"]
    for k, name in enumerate(CLASSES):
        p, r, f1, n = prf(yte, pred, k)
        md.append("| %s | %.3f | %.3f | %.3f | %d |" % (name, p, r, f1, n))
    md += ["", "## Confusion matrix (rows = true, columns = predicted)", "",
           "| | " + " | ".join(CLASSES) + " |", "|" + " --- |" * (len(CLASSES) + 1)]
    for k, name in enumerate(CLASSES):
        md.append("| %s | " % name + " | ".join(str(int(np.sum((yte == k) & (pred == j))))
                                                for j in range(len(CLASSES))) + " |")
    md += ["", "## Alarms per test capture (learned rules + %d-window persistence)" % 3, "",
           "| capture | scenario | first attack window | first alarm window | delay (ms) | false alarm windows |",
           "| --- | --- | --- | --- | --- | --- |"]
    for e, X, y in te:
        out = run_detector(rules, X.tolist())
        alarms = np.array([o[6] for o in out])
        fa, fl, dl, fp = alarm_stats(alarms, y)
        md.append("| %s | %s | %d | %d | %s | %d |" % (capture_name(e), e["scenario"], fa, fl,
                                                        "-" if dl is None else dl, fp))
    md += ["", "## Comparison: teammates' hand rule (modbus >= %d for %d windows)"
           % (HAND_RULE["min"], HAND_RULE["persist"]), "",
           "| capture | scenario | first alarm window | delay (ms) | false alarm windows |",
           "| --- | --- | --- | --- | --- |"]
    for e, X, y in te:
        if e["scenario"] not in ("normal", "modbus_flood"):
            continue
        alarms = hand_rule_alarms(X)
        fa, fl, dl, fp = alarm_stats(alarms, y)
        md.append("| %s | %s | %d | %s | %d |" % (capture_name(e), e["scenario"], fl,
                                                   "-" if dl is None else dl, fp))
    md.append("")
    with open(os.path.join(base, "results", "detection_metrics.md"), "w") as f:
        f.write("\n".join(md))

    for name, (e, X, y) in data.items():
        plot(os.path.join(base, "results", "window_counts_%s.png" % name), name, X, y)

    print("\n".join(open(os.path.join(root, "results", "learned_rules.txt")).read().splitlines()))
    print("\n".join(md))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
